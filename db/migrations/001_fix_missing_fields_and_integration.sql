CREATE SEQUENCE comprobante_id_comprobante_seq;
CREATE TABLE comprobante (
  id_comprobante     integer PRIMARY KEY DEFAULT nextval('comprobante_id_comprobante_seq'),
  id_pago            integer NOT NULL UNIQUE REFERENCES pago(id_pago),
  numero_comprobante varchar(20) NOT NULL UNIQUE,
  fecha_emision      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  monto_total        numeric(10,2) NOT NULL
);
ALTER SEQUENCE comprobante_id_comprobante_seq OWNED BY comprobante.id_comprobante;

CREATE OR REPLACE FUNCTION fn_emitir_comprobante() RETURNS trigger AS $$
DECLARE v_id integer;
BEGIN
  IF NEW.estado_pago = 'Aprobado'
     AND NOT EXISTS (SELECT 1 FROM comprobante WHERE id_pago = NEW.id_pago) THEN
    v_id := nextval('comprobante_id_comprobante_seq');
    INSERT INTO comprobante (id_comprobante, id_pago, numero_comprobante, fecha_emision, monto_total)
    VALUES (v_id, NEW.id_pago, 'COMP-' || lpad(v_id::text, 6, '0'), NEW.fecha_pago, NEW.monto_total);
  END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_emitir_comprobante
AFTER INSERT OR UPDATE ON pago
FOR EACH ROW EXECUTE FUNCTION fn_emitir_comprobante();

